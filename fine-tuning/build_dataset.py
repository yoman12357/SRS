def deterministic_source_split(
    source_ids: list[str],
    train_ratio: float,
    val_ratio: float,
    seed: int,
) -> dict[str, str]:
    ids = sorted(set(source_ids))
    rng = random.Random(seed)
    rng.shuffle(ids)

    n = len(ids)
    if n == 0:
        return {}

    n_train = int(round(n * train_ratio))
    n_val = int(round(n * val_ratio))

    # Ensure non-empty val/test when enough documents exist.
    if n >= 10:
        n_val = max(1, n_val)
        n_test = max(1, n - n_train - n_val)
        if n_train + n_val + n_test > n:
            n_train = n - n_val - n_test
    else:
        n_test = max(0, n - n_train - n_val)

    split: dict[str, str] = {}
    for sid in ids[:n_train]:
        split[sid] = "train"
    for sid in ids[n_train:n_train + n_val]:
        split[sid] = "validation"
    for sid in ids[n_train + n_val:]:
        split[sid] = "test"

    # Defensive fallback.
    for sid in ids:
        split.setdefault(sid, "train")

    return split


