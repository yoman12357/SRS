def check_ollama(base_url: str, model: str, timeout: int) -> None:
    try:
        r = requests.get(f"{base_url.rstrip('/')}/api/tags", timeout=min(timeout, 20))
        r.raise_for_status()
    except Exception as exc:
        raise RuntimeError(
            f"Cannot reach Ollama at {base_url}. Start Ollama first."
        ) from exc

    data = r.json()
    names = {m.get("name", "") for m in data.get("models", [])}
    # Ollama may report tags with or without exact alias formatting.
    if model not in names and not any(n.startswith(model + ":") for n in names):
        logging.warning(
            "Model '%s' was not found in `ollama list`. Available models include: %s",
            model,
            ", ".join(sorted(names)[:12]) or "(none)",
        )


def call_ollama(
    base_url: str,
    model: str,
    source_text: str,
    category: str,
    timeout: int,
    temperature: float,
    retries: int,
) -> dict[str, Any]:
    url = f"{base_url.rstrip('/')}/api/chat"

    user_prompt = f"""DOMAIN: Cybersecurity & Network Infrastructure
SOURCE CATEGORY: {category}

{TASK_GUIDANCE}

SOURCE EXCERPT:
--- BEGIN EXCERPT ---
{source_text}
--- END EXCERPT ---
"""

    payload = {
        "model": model,
        "stream": False,
        "format": "json",
        "messages": [
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user", "content": user_prompt},
        ],
        "options": {
            "temperature": temperature,
            "top_p": 0.9,
            "num_ctx": 32768,
        },
    }

    last_error: Exception | None = None

    for attempt in range(retries + 1):
        try:
            response = requests.post(url, json=payload, timeout=timeout)
            response.raise_for_status()
            body = response.json()
            content = body.get("message", {}).get("content", "")
            if not content:
                raise ValueError("Ollama returned an empty message.")

            return parse_model_json(content)

        except Exception as exc:
            last_error = exc
            if attempt >= retries:
                break

            delay = min(2 ** attempt * 2, 20)
            logging.warning(
                "Generation failed (attempt %d/%d): %s. Retrying in %ds...",
                attempt + 1,
                retries + 1,
                exc,
                delay,
            )
            time.sleep(delay)

    raise RuntimeError(f"Ollama generation failed: {last_error}")


def parse_model_json(content: str) -> dict[str, Any]:
    """
    Parse strict JSON but tolerate accidental markdown fences or surrounding text.
    """
    content = content.strip()
    content = re.sub(r"^```(?:json)?\s*", "", content, flags=re.I)
    content = re.sub(r"\s*```$", "", content)

    try:
        obj = json.loads(content)
        if isinstance(obj, dict):
            return obj
    except json.JSONDecodeError:
        pass

    # Salvage the largest-looking JSON object.
    start = content.find("{")
    end = content.rfind("}")
    if start != -1 and end != -1 and end > start:
        obj = json.loads(content[start:end + 1])
        if isinstance(obj, dict):
            return obj

    raise ValueError("Model output was not a JSON object.")


