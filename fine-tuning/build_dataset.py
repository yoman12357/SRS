ALLOWED_TASKS = {
    "project_analysis",
    "clarification_questions",
    "srs_requirements",
    "threat_model_architecture",
}


def normalize_example(raw: Any) -> dict[str, str] | None:
    if not isinstance(raw, dict):
        return None

    task = str(raw.get("task", "")).strip()
    user = str(raw.get("user", "")).strip()
    assistant = str(raw.get("assistant", "")).strip()

    if task not in ALLOWED_TASKS:
        return None
    if len(user) < 40 or len(assistant) < 100:
        return None

    # Remove accidental surrounding markdown fences only.
    user = re.sub(r"^```.*?\n|\n```$", "", user, flags=re.S).strip()
    assistant = re.sub(r"^```.*?\n|\n```$", "", assistant, flags=re.S).strip()

    forbidden = [
        "source excerpt",
        "provided document",
        "training data",
        "as an ai language model",
    ]
    combined = (user + "\n" + assistant).lower()
    if any(x in combined for x in forbidden):
        return None

    # Avoid obviously broken output.
    if assistant.count("{") != assistant.count("}"):
        # This is only a weak signal and requirements may contain braces, so reject
        # only when the imbalance is large.
        if abs(assistant.count("{") - assistant.count("}")) > 2:
            return None

    return {
        "task": task,
        "user": user,
        "assistant": assistant,
    }


def examples_from_response(response: dict[str, Any]) -> list[dict[str, str]]:
    raw_examples = response.get("examples", [])
    if not isinstance(raw_examples, list):
        return []

    cleaned: list[dict[str, str]] = []
    local_hashes: set[str] = set()

    for raw in raw_examples:
        ex = normalize_example(raw)
        if not ex:
            continue

        h = sha256_text(ex["task"] + "\n" + ex["user"] + "\n" + ex["assistant"])
        if h in local_hashes:
            continue

        local_hashes.add(h)
        ex["example_hash"] = h
        cleaned.append(ex)

    return cleaned[:4]


