def discover_documents(source_root: Path) -> list[Path]:
    docs = []
    for p in source_root.rglob("*"):
        if not p.is_file():
            continue
        if p.name.lower() in SKIP_FILENAMES:
            continue
        if p.suffix.lower() in SUPPORTED_EXTENSIONS:
            docs.append(p)
    return sorted(docs, key=lambda p: str(p).lower())


def reset_outputs(dataset_dir: Path, extracted_dir: Path) -> None:
    for filename in [
        "master_dataset.jsonl",
        "train.jsonl",
        "validation.jsonl",
        "test.jsonl",
        "dataset_manifest.csv",
        "failed_items.jsonl",
        "progress.json",
    ]:
        p = dataset_dir / filename
        if p.exists():
            p.unlink()

    if extracted_dir.exists():
        for p in extracted_dir.rglob("*.txt"):
            try:
                p.unlink()
            except OSError:
                pass


def load_existing_hashes(master_path: Path) -> set[str]:
    hashes = set()
    if not master_path.exists():
        return hashes

    with master_path.open("r", encoding="utf-8") as f:
        for line in f:
            try:
                obj = json.loads(line)
                h = obj.get("example_hash")
                if h:
                    hashes.add(h)
            except Exception:
                continue
    return hashes


def write_split_files(
    master_path: Path,
    dataset_dir: Path,
    source_split: dict[str, str],
) -> dict[str, int]:
    out_paths = {
        "train": dataset_dir / "train.jsonl",
        "validation": dataset_dir / "validation.jsonl",
        "test": dataset_dir / "test.jsonl",
    }

    for p in out_paths.values():
        p.write_text("", encoding="utf-8")

    counts = {"train": 0, "validation": 0, "test": 0}

    if not master_path.exists():
        return counts

    with master_path.open("r", encoding="utf-8") as src:
        for line in src:
            try:
                obj = json.loads(line)
            except Exception:
                continue

            split = source_split.get(obj.get("source_id", ""), "train")
            obj["split"] = split

            # Chat-style dataset compatible with common SFT workflows.
            training_row = {
                "messages": [
                    {
                        "role": "system",
                        "content": (
                            "You are CyberSRS, an AI software requirements architect "
                            "specialized in Cybersecurity and Network Infrastructure. "
                            "Produce clear, testable, security-aware requirements and "
                            "engineering analysis. Do not invent unsupported facts."
                        ),
                    },
                    {"role": "user", "content": obj["user"]},
                    {"role": "assistant", "content": obj["assistant"]},
                ],
                "task": obj["task"],
                "source_id": obj["source_id"],
                "source_file": obj["source_file"],
                "source_category": obj["source_category"],
                "chunk_index": obj["chunk_index"],
                "example_hash": obj["example_hash"],
            }

            jsonl_append(out_paths[split], training_row)
            counts[split] += 1

    return counts


def write_manifest(
    path: Path,
    source_records: list[dict[str, Any]],
    source_split: dict[str, str],
) -> None:
    fieldnames = [
        "source_id",
        "source_file",
        "source_category",
        "split",
        "extracted_chars",
        "total_chunks",
        "processed_chunks",
        "generated_examples",
        "status",
    ]

    with path.open("w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        for record in source_records:
            row = {k: record.get(k, "") for k in fieldnames}
            row["split"] = source_split.get(record["source_id"], "train")
            writer.writerow(row)


