def split_paragraphs(text: str) -> list[str]:
    paragraphs = []
    for part in re.split(r"\n\s*\n+", text):
        part = re.sub(r"\s*\n\s*", " ", part).strip()
        if part:
            paragraphs.append(part)
    return paragraphs


def chunk_text(
    text: str,
    target_chars: int = 7000,
    overlap_chars: int = 700,
    min_chars: int = 900,
) -> list[str]:
    """
    Paragraph-aware character chunking.

    Character chunking is intentionally used here so the script has no tokenizer
    dependency. Around 7k characters is generally small enough to leave room for
    prompts and generated examples in a 32k context.
    """
    paragraphs = split_paragraphs(text)
    if not paragraphs:
        return []

    chunks: list[str] = []
    current: list[str] = []
    current_len = 0

    for para in paragraphs:
        # If a single paragraph is extremely long, split it.
        if len(para) > target_chars * 2:
            if current:
                joined = "\n\n".join(current).strip()
                if len(joined) >= min_chars:
                    chunks.append(joined)
                current = []
                current_len = 0

            start = 0
            while start < len(para):
                end = min(start + target_chars, len(para))
                piece = para[start:end].strip()
                if len(piece) >= min_chars:
                    chunks.append(piece)
                if end == len(para):
                    break
                start = max(end - overlap_chars, start + 1)
            continue

        projected = current_len + len(para) + 2
        if current and projected > target_chars:
            joined = "\n\n".join(current).strip()
            if len(joined) >= min_chars:
                chunks.append(joined)

            # Carry a small tail of the previous chunk for context.
            tail = joined[-overlap_chars:].strip() if overlap_chars else ""
            current = [tail, para] if tail else [para]
            current_len = sum(len(x) for x in current) + 2 * (len(current) - 1)
        else:
            current.append(para)
            current_len = projected

    if current:
        joined = "\n\n".join(current).strip()
        if len(joined) >= min_chars:
            chunks.append(joined)

    # Exact deduplication.
    seen = set()
    unique = []
    for chunk in chunks:
        h = sha256_text(chunk)
        if h not in seen:
            seen.add(h)
            unique.append(chunk)

    return unique


def choose_chunks(chunks: list[str], max_chunks: int, seed: int) -> list[tuple[int, str]]:
    """
    Select chunks spread across the whole document rather than only the beginning.
    """
    indexed = list(enumerate(chunks))
    if max_chunks <= 0 or len(indexed) <= max_chunks:
        return indexed

    # Evenly spaced selection across the document.
    if max_chunks == 1:
        positions = [len(indexed) // 2]
    else:
        positions = [
            round(i * (len(indexed) - 1) / (max_chunks - 1))
            for i in range(max_chunks)
        ]

    # Preserve order and uniqueness.
    selected = []
    used = set()
    for pos in positions:
        pos = max(0, min(pos, len(indexed) - 1))
        if pos not in used:
            selected.append(indexed[pos])
            used.add(pos)

    return selected


