#!/usr/bin/env python3
"""
CyberSRS fine-tuning dataset builder
====================================

Purpose
-------
Recursively reads documents from:

    finetuning/source_documents/

and automatically creates:

    finetuning/extracted_text/
    finetuning/dataset/master_dataset.jsonl
    finetuning/dataset/train.jsonl
    finetuning/dataset/validation.jsonl
    finetuning/dataset/test.jsonl
    finetuning/dataset/dataset_manifest.csv
    finetuning/dataset/failed_items.jsonl
    finetuning/dataset/progress.json

The training examples are generated by your LOCAL Ollama Qwen model.

Recommended project layout
--------------------------
CyberSRS/
└── finetuning/
    ├── source_documents/
    │   └── ... your 200 documents/subfolders ...
    └── build_dataset.py

Install dependencies
--------------------
    pip install requests pypdf python-docx beautifulsoup4

Make sure Ollama is running and the model exists:
    ollama list

Run from the CyberSRS root:
    python finetuning/build_dataset.py

Or run from inside finetuning/:
    python build_dataset.py

Useful options
--------------
    python finetuning/build_dataset.py --help
    python finetuning/build_dataset.py --model qwen3:4b-instruct-2507-q4_K_M
    python finetuning/build_dataset.py --max-chunks-per-doc 3
    python finetuning/build_dataset.py --reset
    python finetuning/build_dataset.py --extract-only

Notes
-----
1. This script creates supervised fine-tuning examples; it does NOT fine-tune the model.
2. It deliberately splits by SOURCE DOCUMENT, not by generated sample, to reduce train/test leakage.
3. It checkpoints progress so an interrupted run can be resumed.
4. Automatic generation should still be reviewed before final training.
"""

