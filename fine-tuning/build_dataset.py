def sha256_text(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8", errors="ignore")).hexdigest()


def jsonl_append(path: Path, obj: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a", encoding="utf-8") as f:
        f.write(json.dumps(obj, ensure_ascii=False) + "\n")


def load_json(path: Path, default: Any) -> Any:
    if not path.exists():
        return default
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except Exception:
        return default


def save_json(path: Path, obj: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(json.dumps(obj, ensure_ascii=False, indent=2), encoding="utf-8")
    tmp.replace(path)


def clean_text(text: str) -> str:
    """Normalize extracted text without aggressively changing technical content."""
    text = html.unescape(text)
    text = text.replace("\x00", " ")
    text = text.replace("\u00ad", "")  # soft hyphen
    text = text.replace("\r\n", "\n").replace("\r", "\n")

    # Join words broken across line endings: "authenti-\ncation" -> "authentication".
    text = re.sub(r"([A-Za-z])-\n([a-z])", r"\1\2", text)

    # Reduce repeated spaces/tabs.
    text = re.sub(r"[ \t]+", " ", text)

    # Remove excessive blank lines.
    text = re.sub(r"\n{3,}", "\n\n", text)

    # Remove obvious isolated page-number lines.
    text = re.sub(r"(?m)^\s*(?:page\s+)?\d+\s*(?:of\s+\d+)?\s*$", "", text, flags=re.I)

    # Normalize line spacing again.
    text = re.sub(r"\n{3,}", "\n\n", text)

    return text.strip()


def infer_category(source_path: Path, source_root: Path) -> str:
    """
    Use the first subfolder under source_documents as category.
    Example:
      source_documents/network_security/file.pdf -> network_security
    """
    try:
        rel = source_path.relative_to(source_root)
        if len(rel.parts) > 1:
            return rel.parts[0]
    except ValueError:
        pass
    return "general"


